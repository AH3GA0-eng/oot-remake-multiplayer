"""Writes lichii/hook/coop_difficulty_spots.inc: where extra enemies may stand, from the game's placements.

    python -m puppet_pack.extra_spots --romfs <romfs> --out lichii/hook/coop_difficulty_spots.inc

Difficulty's "more enemies" (docs/play-online.md, "Difficulty") makes extra copies of placed
enemies. The module has no ground or navmesh query of the game, so an extra may only stand where
the game's own data says there is floor: on a placed floor marker of the same area. Those are

- `DestinationAnchor`: where the game puts Link down (a door, an entrance, a warp's landing),
- `WarpSafePosAnchor`: where the game puts Link back after a fall,
- `StartPos`: where Link starts in the area,
- `Obj_Plant_Grass_*`: a tuft of grass on the floor (cut through, nothing to stand inside).

For each area (a Banc scene, its Static and Dynamic placements together) the table lists its
placed enemies (placement hash, actor, where it is placed) and the markers that lie near one of
them (within REACH_M across, STEP_M up or down): the module (coop_difficulty.cpp PlanArea) picks
the spots from this table only, so every game picks the same ones whatever it has loaded.
"""
import argparse
import os
import sys

if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    __package__ = "puppet_pack"  # noqa: A001

from .designed_enemies import is_enemy, scene_actors, u64  # noqa: E402

GROUND_EXACT = ("DestinationAnchor", "WarpSafePosAnchor", "StartPos")
GROUND_PREFIX = ("Obj_Plant_Grass_",)
REACH_M = 8.0  # the same numbers as coop_difficulty.h kSpotReachM / kSpotStepM
STEP_M = 1.0


def is_ground(gyaml):
    return gyaml in GROUND_EXACT or gyaml.startswith(GROUND_PREFIX)


def at(actor):
    t = actor.get("Translate") or [0.0, 0.0, 0.0]
    return (float(t[0]), float(t[1]), float(t[2]))


def near(a, b):
    return (a[0] - b[0]) ** 2 + (a[2] - b[2]) ** 2 <= REACH_M * REACH_M and abs(a[1] - b[1]) <= STEP_M


def areas(scenes):
    """[(scene, [(hash, gyaml, at)], [at])]: each area's placed enemies and the markers near one of them."""
    out = []
    for scene in sorted(scenes):
        enemies, ground = [], []
        for a in scenes[scene]:
            g = str(a.get("Gyaml", ""))
            h = u64(a.get("Hash"))
            if is_enemy(g) and h not in (0, (1 << 64) - 1):
                enemies.append((h, g, at(a)))
            elif is_ground(g):
                ground.append(at(a))
        enemies.sort()
        ground = sorted({p for p in ground if any(near(p, e[2]) for e in enemies)})
        if enemies:
            out.append((scene, enemies, ground))
    return out


def f(v):
    return f"{v:.3f}f"


def render(found):
    lines = [
        "// Generated by tools/puppet_pack/extra_spots.py from the game's Banc placements; do not edit.",
        "// Each area's placed enemies (placement hash, actor, placed at) and the floor markers near them",
        "// (DestinationAnchor, WarpSafePosAnchor, StartPos, grass): where extra enemies may stand",
        "// (coop_difficulty.cpp PlanArea).",
        "constexpr SpotEnemy kSpotEnemies[] = {",
    ]
    scenes, ne, ng = [], 0, 0
    for scene, enemies, ground in found:
        lines.append(f"    // {scene}")
        for h, g, p in enemies:
            lines.append(f'    {{0x{h:016x}ull, "{g}", {{{f(p[0])}, {f(p[1])}, {f(p[2])}}}}},')
        scenes.append((scene, ne, ne + len(enemies), ng, ng + len(ground)))
        ne += len(enemies)
        ng += len(ground)
    lines.append("};")
    lines.append("constexpr SpotPoint kSpotGround[] = {")
    for scene, _, ground in found:
        if ground:
            lines.append(f"    // {scene}")
        for p in ground:
            lines.append(f"    {{{f(p[0])}, {f(p[1])}, {f(p[2])}}},")
    lines.append("    {0.0f, 0.0f, 0.0f},  // (never empty; no area points here)")
    lines.append("};")
    lines.append("constexpr SpotArea kSpotAreas[] = {")
    for scene, e0, e1, g0, g1 in scenes:
        lines.append(f'    {{"{scene}", {e0}, {e1}, {g0}, {g1}}},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--romfs", required=True, help="your own extracted game (holds Banc)")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    found = areas(scene_actors(args.romfs))
    with open(args.out, "w", newline="\n") as fh:
        fh.write(render(found))
    print(f"{len(found)} areas, {sum(len(e) for _, e, _ in found)} enemies, "
          f"{sum(len(g) for _, _, g in found)} floor markers")


if __name__ == "__main__":
    main()
